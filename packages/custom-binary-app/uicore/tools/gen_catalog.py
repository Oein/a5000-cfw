#!/usr/bin/env python3
"""Generate the SettingsCatalog subset used by the shooting OSD (M1) from
app/docs/settings_sdcom_map.tsv  (SDCom 0x1002/0x1003 param ids, A-side values).

  python3 -I uicore/tools/gen_catalog.py --tsv app/docs/settings_sdcom_map.tsv \
      --out-h uicore/include/uicore/catalog_gen.h --out-cpp uicore/src/model/catalog_gen.cpp

Only the settings listed in SUBSET are emitted; M2 widens the list (same tool).
Enum rows are kept when the TSV notes say 'a5k-supported' (or carry no 'not in ...'
marker); rows with sdcom_value '-' (app label only) are dropped.  The TSV is data
derived from the camera firmware: the generated files carry no pixels or strings
beyond HAL value names (facts).
"""
import argparse, re, sys

# (C name, tsv setting_id, kind, paramId override or None)
#  kind: ENUM | INT | BOOL | RO_INT | RO_ARR2
SUBSET = [
    ("EXPOSURE_MODE", "api:mode/sceneMode",     "ENUM", None),
    ("EV",            "exposure-compensation",  "INT",  None),
    ("ISO",           "iso-sensitivity",        "LIST", None),
    ("DRIVE",         "drive-mode",             "ENUM", None),
    ("SELF_TIMER",    "api:selfTimer",          "LIST", None),
    ("FOCUS_MODE",    "focus-mode",             "ENUM", None),
    ("AF_MODE",       "af-mode",                "ENUM", None),
    ("FOCUS_AREA",    "focus-area-type",        "ENUM", None),
    ("METERING",      "metering-mode",          "ENUM", None),
    ("WB",            "whitebalance",           "ENUM", None),
    ("STORAGE_FMT",   "storage-fmt",            "ENUM", None),
    ("AE_LOCK",       "ae-lock",                "ENUM", None),
]
# Read-only values the OSD needs that the TSV only lists as unlabeled ids.
#  267: aperture x100 (reference 0x1002 dump: 180 with an F1.8 lens; Track A uses
#       modifier.getAperture()/100).  [? id->meaning inferred, verified in M1 emulator run]
#  268: shutter speed IntArray [num, den] (dump: [1,640]; TSV: 'shutter-speed-nume').
EXTRA = [
    ("APERTURE", "aperture-x100", "RO_INT",  267),
    ("SHUTTER",  "shutter-speed", "RO_ARR2", 268),
]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tsv", required=True)
    ap.add_argument("--out-h", required=True)
    ap.add_argument("--out-cpp", required=True)
    a = ap.parse_args()

    rows = {}
    with open(a.tsv, encoding="utf-8") as f:
        hdr = f.readline().rstrip("\n").split("\t")
        for line in f:
            c = line.rstrip("\n").split("\t")
            if len(c) < 8:
                continue
            rows.setdefault(c[0], []).append(c)

    defs = []
    for name, sid, kind, pid_over in SUBSET:
        rs = rows.get(sid)
        if not rs:
            sys.exit("missing setting in TSV: %s" % sid)
        pid = int(rs[0][3])
        d = dict(name=name, key=sid, pid=pid, kind=kind, vals=[], lo=0, hi=0)
        if kind == "ENUM":
            for r in rs:
                if r[4] in ("-", ""):
                    continue
                if "not in" in r[7] and "a5k-supported" not in r[7]:
                    continue
                d["vals"].append((r[2], int(r[4])))
        elif kind == "LIST":
            m = re.search(r"values ([0-9,]+)", rs[0][7])
            if not m:
                sys.exit("no value list for %s" % sid)
            for v in m.group(1).split(","):
                d["vals"].append(("AUTO" if (name == "ISO" and v == "0") else v, int(v)))
        elif kind == "INT":
            m = re.search(r"range (-?\d+)\.\.(-?\d+)", rs[0][7])
            if not m:
                sys.exit("no range for %s" % sid)
            d["lo"], d["hi"] = int(m.group(1)), int(m.group(2))
        defs.append(d)
    for name, key, kind, pid in EXTRA:
        defs.append(dict(name=name, key=key, pid=pid, kind=kind, vals=[], lo=0, hi=0))

    with open(a.out_h, "w") as h:
        h.write("// Generated by uicore/tools/gen_catalog.py from app/docs/settings_sdcom_map.tsv -- do not edit.\n")
        h.write("#pragma once\n\nnamespace uicore {\n\nenum SettingId {\n    SET_NONE = 0,\n")
        for d in defs:
            h.write("    SET_%s,\n" % d["name"])
        h.write("    SET_COUNT\n};\n\n} // namespace uicore\n")

    with open(a.out_cpp, "w") as c:
        c.write("// Generated by uicore/tools/gen_catalog.py from app/docs/settings_sdcom_map.tsv -- do not edit.\n")
        c.write('#include "uicore/catalog.h"\n\nnamespace uicore {\nnamespace {\n\n')
        for d in defs:
            if d["vals"]:
                c.write("const EnumVal kVals_%s[] = {\n" % d["name"])
                for lab, v in d["vals"]:
                    c.write('    { "%s", %d },\n' % (lab, v))
                c.write("};\n")
        c.write("\n} // namespace\n\nconst SettingDef kCatalog[SET_COUNT] = {\n")
        c.write('    { SET_NONE, "", 0, SK_RO_INT, 0, 0, 0, 0 },\n')
        for d in defs:
            vals = ("kVals_%s" % d["name"]) if d["vals"] else "0"
            c.write('    { SET_%s, "%s", %d, SK_%s, %d, %d, %s, %d },\n' %
                    (d["name"], d["key"], d["pid"], d["kind"], d["lo"], d["hi"], vals, len(d["vals"])))
        c.write("};\n\n} // namespace uicore\n")

if __name__ == "__main__":
    main()
